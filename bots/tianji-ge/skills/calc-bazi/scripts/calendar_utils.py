def get_shi_shen(gan, day_master):
    """
    十神判定（基于五行生克，非位置差法）
    
    同我→比肩(同阴阳)/劫财(异阴阳)
    生我→偏印(同阴阳)/正印(异阴阳)
    我生→食神(同阴阳)/伤官(异阴阳)
    克我→七杀(同阴阳)/正官(异阴阳)
    我克→偏财(同阴阳)/正财(异阴阳)
    """
    dm_wx = GAN_WUXING_MAP[day_master]
    g_wx = GAN_WUXING_MAP[gan]
    dm_yang = GAN_YIN_YANG[day_master]
    g_yang = GAN_YIN_YANG[gan]
    
    sk = WUXING_SHENG_KE[(dm_wx, g_wx)]
    same_yinyang = (dm_yang == g_yang)
    
    if sk == 0:
        # 同我
        return "比肩" if same_yinyang else "劫财"
    elif sk == 1:
        # 我生（日主生天干）
        return "食神" if same_yinyang else "伤官"
    elif sk == -1:
        # 生我（天干生日主）
        return "偏印" if same_yinyang else "正印"
    elif sk == 2:
        # 我克（日主克天干）
        return "偏财" if same_yinyang else "正财"
    elif sk == -2:
        # 克我（天干克日主）
        return "七杀" if same_yinyang else "正官"
    return ""


