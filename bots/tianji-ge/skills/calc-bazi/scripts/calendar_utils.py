def get_year_gan_zhi(year, dt):
    """年柱（立春分界）"""
    li_chun = LI_CHUN_DATES.get(year, date(year, 2, 4))
    real_year = year if dt >= li_chun else year - 1
    idx = (real_year - 4) % 60
    return LIU_JIA_ZI[idx], real_year


# ============================================================
# 十五、月柱计算
# ============================================================

def get_month_gan_zhi(year_gan, month, day):
    """月柱（节气分界 + 五虎遁）"""
    thresh, zhi_idx = MONTH_ZHI_MAP[month]

    if day < thresh:
        # 退回到上个月
        prev_month = month - 1 if month > 1 else 12
        _, zhi_idx = MONTH_ZHI_MAP[prev_month]

    # 五虎遁求天干
    first_gan = WU_HU_DUN[year_gan]
    first_idx = TIAN_GAN.index(first_gan)
    # 寅月(索引2)=正月，正月天干=first_gan
    # 子月(索引0) relative to 寅月 = (0-2+12)%12 = 10 steps forward
    month_offset = (zhi_idx - 2) % 12
    gan_idx = (first_idx + month_offset) % 10
    month_gan = TIAN_GAN[gan_idx]
    month_zhi = DI_ZHI[zhi_idx]

    return month_gan + month_zhi


# ============================================================
# 十六、时柱计算
# ============================================================

def get_hour_gan_zhi(day_gan, hour, minute, tz_offset=0):
    """时柱（五鼠遁 + 真太阳时）"""
    # 真太阳时校正
    total_min = hour * 60 + minute + tz_offset
    total_min %= 1440  # 循环到同一天
    adj_hour = total_min // 60

    # 时辰判定（精确到小时）
    if adj_hour == 23 or adj_hour == 0:
        zhi_idx = 0  # 子时
    elif adj_hour == 1 or adj_hour == 2:
        zhi_idx = 1  # 丑
    elif adj_hour == 3 or adj_hour == 4:
        zhi_idx = 2  # 寅
    elif adj_hour == 5 or adj_hour == 6:
        zhi_idx = 3  # 卯
    elif adj_hour == 7 or adj_hour == 8:
        zhi_idx = 4  # 辰
    elif adj_hour == 9 or adj_hour == 10:
        zhi_idx = 5  # 巳
    elif adj_hour == 11 or adj_hour == 12:
        zhi_idx = 6  # 午
    elif adj_hour == 13 or adj_hour == 14:
        zhi_idx = 7  # 未
    elif adj_hour == 15 or adj_hour == 16:
        zhi_idx = 8  # 申
    elif adj_hour == 17 or adj_hour == 18:
        zhi_idx = 9  # 酉
    elif adj_hour == 19 or adj_hour == 20:
        zhi_idx = 10 # 戌
    else:
        zhi_idx = 11 # 亥(21-22)

    # 五鼠遁
    zi_gan = WU_SHU_DUN[day_gan]
    gan_idx = (TIAN_GAN.index(zi_gan) + zhi_idx) % 10
    return TIAN_GAN[gan_idx] + DI_ZHI[zhi_idx], adj_hour, total_min % 60


